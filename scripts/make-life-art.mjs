for (const [name, rows] of Object.entries(art)) {
  if (rows.length !== 16 || rows.some(r => r.length !== 16)) throw new Error(`${name} must be 16x16`);
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const c = row[x];
      if (c === '.') continue;
      const fill = palette[c];
      if (!fill) throw new Error(`${name}: unknown colour ${c}`);
      rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`;
    }
  });
  writeFileSync(`public/art/life/${name}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="80" height="80" shape-rendering="crispEdges">${rects}</svg>\n`);
}
console.log(`wrote ${Object.keys(art).length} icons`);
